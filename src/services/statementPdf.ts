import type { Transaction } from "../types/finance";

export interface PdfInput {
  rows: Transaction[];
  accountName: (id: string) => string;
  categoryName: (id: string | null) => string;
  from: string;
  to: string;
  accountLabel: string;
  income: number;
  expense: number;
}

// The built-in PDF font has no rupee glyph, so the PDF uses "Rs." instead of ₹.
const num = (paise: number) => new Intl.NumberFormat("en-IN", { minimumFractionDigits: 2, maximumFractionDigits: 2 }).format(paise / 100);

export async function generateStatementPdf(input: PdfInput): Promise<void> {
  const [{ jsPDF }, autoTableModule] = await Promise.all([import("jspdf"), import("jspdf-autotable")]);
  const autoTable = autoTableModule.default;

  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const generated = new Date().toLocaleString("en-IN", { dateStyle: "medium", timeStyle: "short" });

  doc.setFontSize(16);
  doc.text("CüS Treasure - Statement of recorded transactions", 40, 48);
  doc.setFontSize(9);
  doc.text(`Period: ${input.from} to ${input.to}    Account: ${input.accountLabel}`, 40, 66);
  doc.text(`Total income: Rs. ${num(input.income)}    Total expenses: Rs. ${num(input.expense)}    Net: Rs. ${num(input.income - input.expense)}`, 40, 80);
  doc.text("Generated by CüS Treasure from transactions you recorded. This is not an official bank statement.", 40, 94);

  autoTable(doc, {
    startY: 108,
    head: [["Date", "Description", "Category", "Account", "Amount (Rs.)"]],
    body: input.rows.map((t) => [
      t.occurred_on,
      t.merchant ? `${t.description} (${t.merchant})` : t.description,
      input.categoryName(t.category_id),
      input.accountName(t.account_id),
      `${t.type === "income" ? "+" : "-"}${num(t.amount_paise)}`,
    ]),
    styles: { fontSize: 8, cellPadding: 4 },
    headStyles: { fillColor: [35, 39, 60] },
    columnStyles: { 4: { halign: "right" } },
    showHead: "everyPage",
  });

  const pages = doc.getNumberOfPages();
  for (let i = 1; i <= pages; i++) {
    doc.setPage(i);
    doc.setFontSize(8);
    doc.text(`Page ${i} of ${pages} - generated ${generated}`, 40, doc.internal.pageSize.getHeight() - 24);
  }
  doc.save(`cus-treasure-statement-${input.from}_to_${input.to}.pdf`);
}